import { expect, test } from '@playwright/test'
import { freezeInputClock, transmit } from './transmission'

test('keyboard navigation into Morse practice sends the first Space to the transmitter', async ({ page }) => {
  await page.goto('converter/')
  await page.getByRole('link', { name: '摩尔斯训练' }).press('Enter')
  const key = page.getByRole('button', { name: /SPACE/ })
  await expect(key).toBeFocused()
  await freezeInputClock(page)
  await transmit(page, '.')
  await expect(page.locator('[aria-current="step"]')).toHaveAttribute('data-char', 'V')
  const reference = page.getByRole('button', { name: '摩尔斯速查表' })
  await reference.press('Space')
  await expect(page.getByRole('dialog', { name: '摩尔斯速查表' })).toBeVisible()
})

test('English caret navigation keeps typing and backspace aligned with the highlighted character', async ({ page }) => {
  await page.goto('latin/')
  await page.getByRole('button', { name: '重新开始' }).click()
  const editor = page.getByRole('textbox', { name: '英文练习输入' })
  await editor.pressSequentially('I ')
  await editor.press('Home')
  await editor.press('s')
  await expect(editor).toHaveValue('I s')
  await editor.press('Shift+ArrowLeft')
  await editor.press('e')
  await expect(editor).toHaveValue('I se')
  await editor.press('ArrowLeft')
  await editor.press('Backspace')
  await expect(editor).toHaveValue('I s')
  await expect(page.locator('[data-state="error"]')).toHaveCount(0)
})

test('pasting the complete English sentence does not start or score the exercise', async ({ page }) => {
  await page.goto('latin/')
  await page.getByRole('button', { name: '重新开始' }).click()
  const sentence = await page.locator('.practice-text').getAttribute('aria-label')
  if (!sentence) throw new Error('Missing English sentence')
  await page.getByRole('link', { name: '编码转换' }).click()
  const source = page.getByRole('textbox', { name: '输入文字' })
  await source.fill(sentence)
  await source.press('ControlOrMeta+a')
  await source.press('ControlOrMeta+c')
  await page.getByRole('link', { name: '英文打字' }).click()
  const editor = page.getByRole('textbox', { name: '英文练习输入' })
  await editor.press('ControlOrMeta+v')
  await expect(editor).toHaveValue('')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.metrics dd').last()).toHaveText('00:00')
  await page.keyboard.insertText('I see')
  await expect(editor).toHaveValue('I see')
})

test('dropping text into English practice leaves the current input and progress intact', async ({ page }) => {
  await page.goto('latin/')
  await page.getByRole('button', { name: '重新开始' }).click()
  const editor = page.getByRole('textbox', { name: '英文练习输入' })
  await editor.press('I')
  const accepted = await editor.evaluate((input) => {
    const transfer = new DataTransfer()
    transfer.setData('text/plain', ' see dead people')
    return input.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }))
  })
  expect(accepted).toBe(false)
  await expect(editor).toHaveValue('I')
  await expect(page.getByRole('progressbar', { name: '练习进度' })).toHaveAttribute('value', '1')
})

test('keyboard transmission follows the current letter, rejects invalid signals, and finishes SOS', async ({
  page,
}) => {
  await page.goto('./')
  const next = page.getByRole('button', { name: '换一组' })
  await next.click()
  await page.getByRole('button', { name: /SPACE/ }).focus()
  await freezeInputClock(page)
  await transmit(page, '..--.')
  await expect(page.getByRole('alert')).toContainText('这组点划暂时无法识别')
  await expect(page.getByText('目标 S：· · ·')).toBeVisible()
  await page.getByRole('button', { name: /查看速查表/ }).click()
  const drawer = page.getByRole('dialog', { name: '摩尔斯速查表' })
  await expect(drawer.getByText('−···', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: '数字' }).click()
  await expect(drawer.getByText('·····', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: '标点' }).click()
  await expect(drawer.getByText('··−−··', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveCount(0)
  await page.getByRole('button', { name: /SPACE/ }).focus()
  await transmit(page, '...')
  await expect(page.locator('[aria-current="step"]')).toHaveAttribute('data-char', 'O')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await transmit(page, '---')
  await transmit(page, '...')
  const result = page.getByRole('dialog', { name: '信号已送达。' })
  await expect(result).toContainText('100%')
  await expect(result).toContainText('SOS')
  await result.getByRole('button', { name: '再练一次' }).click()
  await expect(page.locator('[aria-current="step"]')).toHaveAttribute('data-char', 'S')
})

test('English typing tracks real mistakes, correction, focus, restart and completion', async ({ page }) => {
  await page.goto('latin/')
  await expect(page.getByText('94.4', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '重新开始' }).click()
  await page.keyboard.type('X')
  await expect(page.getByText('1 / 117 CHARACTERS')).toBeVisible()
  await expect(page.locator('[data-state="error"]')).toHaveText('I')
  await page.keyboard.press('Backspace')
  await expect(page.locator('[data-state="error"]')).toHaveCount(0)
  await page.keyboard.type('I see ')
  await expect(page.getByText('6 / 117 CHARACTERS')).toBeVisible()
  await page.getByRole('button', { name: '专注模式' }).click()
  await expect(page.getByRole('button', { name: '退出专注' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.keyboard.type(
    "dead people walking around like regular people, they don't see each other, they only see what they want to see."
  )
  const result = page.getByRole('dialog')
  await expect(result).toContainText('100%')
  await result.getByRole('button', { name: '下一组练习' }).click()
  await expect(result).toHaveCount(0)
  await expect(page.locator('[aria-current="step"]')).toHaveAttribute('data-char', /./)
  await expect(page.getByText('0 / 117 CHARACTERS')).toHaveCount(0)
})

test('mobile touch key continues the displayed signal and navigation reaches all three modes', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 })
  await page.goto('./')
  const transmitKey = page.getByRole('button', { name: '按住发报' })
  await expect(transmitKey).toBeVisible()
  await freezeInputClock(page)
  const box = await transmitKey.boundingBox()
  if (!box) throw new Error('Missing transmission key')
  await page.mouse.move(box.x + box.width / 2, box.y + 20)
  await page.mouse.down()
  await page.clock.runFor(200)
  await page.mouse.up()
  await page.clock.runFor(510)
  await expect(page.getByText('03 / 03')).toBeVisible()
  const nav = page.getByRole('navigation')
  await nav.getByRole('link', { name: '英文打字' }).click()
  await expect(page.getByRole('heading', { name: '英文打字' })).toBeVisible()
  await nav.getByRole('link', { name: '编码转换' }).click()
  await expect(page.getByRole('textbox', { name: '输入文字' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('changing theme, sound and language persists across routes and reloads', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('./')
  const favicon = page.locator('head link[rel="icon"]')
  await expect(favicon).toHaveCount(1)
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(favicon).toHaveAttribute('href', /\/favicon\.svg$/)
  await page.getByRole('button', { name: '关闭声音' }).click()
  await page.getByRole('button', { name: '切换到浅色主题' }).click()
  await expect(favicon).toHaveAttribute('href', /\/favicon-light\.svg$/)
  await page.getByRole('button', { name: 'Switch to English' }).click()
  await page.getByRole('link', { name: 'English typing' }).click()
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('English typing')
  await expect(page.getByRole('button', { name: 'Enable sound' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Switch to dark theme' })).toBeVisible()
  await expect(favicon).toHaveAttribute('href', /\/favicon-light\.svg$/)
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await expect(favicon).toHaveAttribute('href', /\/favicon\.svg$/)
})
